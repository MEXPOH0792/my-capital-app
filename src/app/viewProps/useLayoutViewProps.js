import { useMemo } from 'react';
import { buildHeaderProps, buildModalHostProps, buildShellProps, buildSidebarProps } from './layoutProps.js';

export function useLayoutViewProps({
  activeTab,
  copy,
  theme,
  panelStyle,
  softPanelStyle,
  currentSectionMeta,
  pageTitle,
  financeSectionLabel,
  financeGroupLabel,
  setActiveTab,
  isSidebarOpen,
  setIsSidebarOpen,
  primaryNavItems,
  secondaryNavItems,
  setupNavItems,
  insightsGroupLabel,
  isFinanceSection,
  store,
  modalFlow,
  isEnglish,
  allocationModes,
  formatInput,
  selectFieldStyle,
  selectOptionStyle,
  spendableAccounts,
  fmt,
  canDeleteTransaction,
  deleteTransaction,
  canEditTransaction,
  canReverseTransfer,
  reverseTransfer,
}) {
  const shellProps = useMemo(
    () =>
      buildShellProps({
        activeTab,
        copy,
        theme,
        panelStyle,
        softPanelStyle,
        currentSectionMeta,
        pageTitle,
        financeSectionLabel,
        financeGroupLabel,
        setActiveTab,
      }),
    [
      activeTab,
      copy,
      theme,
      panelStyle,
      softPanelStyle,
      currentSectionMeta,
      pageTitle,
      financeSectionLabel,
      financeGroupLabel,
      setActiveTab,
    ],
  );

  const sidebarProps = useMemo(
    () =>
      buildSidebarProps({
        isSidebarOpen,
        setIsSidebarOpen,
        activeTab,
        setActiveTab,
        primaryNavItems,
        secondaryNavItems,
        setupNavItems,
        copy,
        insightsGroupLabel,
        financeGroupLabel,
        theme,
      }),
    [
      isSidebarOpen,
      setIsSidebarOpen,
      activeTab,
      setActiveTab,
      primaryNavItems,
      secondaryNavItems,
      setupNavItems,
      copy,
      insightsGroupLabel,
      financeGroupLabel,
      theme,
    ],
  );

  const headerProps = useMemo(
    () =>
      buildHeaderProps({
        activeTab,
        copy,
        pageTitle,
        financeSectionLabel,
        isFinanceSection,
        store,
        setActiveTab,
        setIsSidebarOpen,
        panelStyle,
        theme,
      }),
    [
      activeTab,
      copy,
      pageTitle,
      financeSectionLabel,
      isFinanceSection,
      store,
      setActiveTab,
      setIsSidebarOpen,
      panelStyle,
      theme,
    ],
  );

  const modalHostProps = useMemo(
    () =>
      buildModalHostProps({
        modalFlow,
        isEnglish,
        store,
        allocationModes,
        theme,
        panelStyle,
        copy,
        formatInput,
        softPanelStyle,
        selectFieldStyle,
        selectOptionStyle,
        spendableAccounts,
        fmt,
        canDeleteTransaction,
        deleteTransaction,
        canEditTransaction,
        canReverseTransfer,
        reverseTransfer,
      }),
    [
      modalFlow,
      isEnglish,
      store,
      allocationModes,
      theme,
      panelStyle,
      copy,
      formatInput,
      softPanelStyle,
      selectFieldStyle,
      selectOptionStyle,
      spendableAccounts,
      fmt,
      canDeleteTransaction,
      deleteTransaction,
      canEditTransaction,
      canReverseTransfer,
      reverseTransfer,
    ],
  );

  return { shellProps, sidebarProps, headerProps, modalHostProps };
}
