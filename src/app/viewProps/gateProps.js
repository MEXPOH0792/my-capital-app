export function buildOnboardingProps({
  copy,
  isEnglish,
  store,
  theme,
  panelStyle,
  softPanelStyle,
  formatInput,
  fmt,
  allocationModes,
  onboarding,
}) {
  return {
    copy,
    isEnglish,
    isDarkMode: store.isDarkMode,
    theme,
    panelStyle,
    softPanelStyle,
    formatInput,
    fmt,
    onboardingStep: onboarding.onboardingStep,
    setOnboardingStep: onboarding.setOnboardingStep,
    balances: onboarding.balances,
    setBalances: onboarding.setBalances,
    accountFields: onboarding.accountFields,
    totalMoney: onboarding.totalMoney,
    debts: onboarding.debts,
    addDebt: onboarding.addDebt,
    updateDebt: onboarding.updateDebt,
    removeDebt: onboarding.removeDebt,
    requiredExpenses: onboarding.requiredExpenses,
    addRequiredExpense: onboarding.addRequiredExpense,
    updateRequiredExpense: onboarding.updateRequiredExpense,
    removeRequiredExpense: onboarding.removeRequiredExpense,
    targets: onboarding.targets,
    setTargets: onboarding.setTargets,
    allocationModes,
    onboardingMode: onboarding.onboardingMode,
    setOnboardingMode: onboarding.setOnboardingMode,
    submitOnboarding: onboarding.submitOnboarding,
    isReconfigureMode: onboarding.isReconfigureMode,
    canExit: onboarding.isReconfigureMode,
    onExit: onboarding.exitReconfigure,
    hasLiveHistory: store.transactions.length > 0,
    toggleTheme: store.toggleTheme,
    setLanguage: store.setLanguage,
  };
}

export function buildLockProps({ isEnglish, store, theme, security }) {
  return {
    isEnglish,
    isDarkMode: store.isDarkMode,
    theme,
    onUnlock: security.unlock,
    pinLockedUntil: security.pinLockedUntil,
    forgotPin: security.forgotPin,
    onToggleTheme: store.toggleTheme,
    onSetLanguage: store.setLanguage,
    biometric: security.biometric,
  };
}
