export function buildSidebarProps({
  isSidebarOpen,
  setIsSidebarOpen,
  activeTab,
  setActiveTab,
  primaryNavItems,
  secondaryNavItems,
  setupNavItems,
  copy,
  insightsGroupLabel,
  financeGroupLabel,
  theme,
}) {
  return {
    isOpen: isSidebarOpen,
    onClose: () => setIsSidebarOpen(false),
    activeTab,
    setActiveTab,
    primaryNavItems,
    secondaryNavItems,
    setupNavItems,
    copy,
    insightsGroupLabel,
    financeGroupLabel,
    theme,
  };
}

export function buildHeaderProps({
  activeTab,
  copy,
  pageTitle,
  financeSectionLabel,
  isFinanceSection,
  store,
  setActiveTab,
  setIsSidebarOpen,
  panelStyle,
  theme,
}) {
  return {
    activeTab,
    copy,
    pageTitle,
    financeSectionLabel,
    isFinanceSection,
    isDarkMode: store.isDarkMode,
    onBackHome: () => setActiveTab('home'),
    onOpenSidebar: () => setIsSidebarOpen(true),
    onToggleTheme: store.toggleTheme,
    panelStyle,
    theme,
  };
}

