import { shouldRemindBackup } from '../../domain/backup.js';

export function buildHomeProps({
  store,
  exportBackup,
  fmt,
  locale,
  primaryStatus,
  secondaryStatus,
  hasActiveDebts,
  advisorInsight,
  previewDistribution,
  progressMilestones,
  goalJourney,
  modalFlow,
}) {
  return {
    store,
    fmt,
    locale,
    primaryStatus,
    secondaryStatus,
    hasActiveDebts,
    advisorInsight,
    previewCapitalGain: previewDistribution.toCapital,
    progressMilestones,
    goalJourney,
    onEditBalance: () => {
      modalFlow.openAmountModal('edit_balance', store.availableBalance);
    },
    onOpenIncome: () => modalFlow.openTransactionModal('income'),
    onOpenExpense: () => modalFlow.openTransactionModal('expense'),
    showBackupReminder: shouldRemindBackup(store.lastBackupAt, store.transactions.length, Date.now()),
    onExportBackup: exportBackup,
  };
}

export function buildDebtProps({
  store,
  fmt,
  isEnglish,
  debtStrategies,
  uncoveredRequired,
  safeDebtPaymentNow,
  suggestedDebtPayment,
  sortedDebts,
  modalFlow,
}) {
  return {
    store,
    fmt,
    isEnglish,
    debtStrategies,
    uncoveredRequired,
    safeDebtPaymentNow,
    suggestedDebtPayment,
    sortedDebts,
    onUseSuggestedPayment: () => {
      modalFlow.openDebtPaymentModal(debtStrategies.recommendedDebt, suggestedDebtPayment);
    },
    onOpenNewDebt: modalFlow.openNewDebtModal,
    onEditDebt: (debt) => {
      modalFlow.openEditDebtModal(debt);
    },
    onPayDebt: (debt) => {
      modalFlow.openDebtPaymentModal(debt);
    },
  };
}

