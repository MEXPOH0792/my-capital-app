export function buildFinanceProps({
  store,
  isEnglish,
  fmt,
  locale,
  backupNotice,
  familyNotice,
  importPartnerReport,
  removePartnerReport,
  removePartner,
  exportBackup,
  importBackup,
  undoImport,
  onboarding,
  security,
  securityForm,
  setSecurityForm,
  securityNotice,
  saveSecurityPin,
  clearSecurityPin,
  lockAppNow,
  showAdvancedDistribution,
  setShowAdvancedDistribution,
  allocationModes,
  setAllocationForm,
  allocationForm,
  handleAllocationInput,
  currentMode,
  payYourselfPercent,
  availableForObligations,
  previewDistribution,
  obligationsDelta,
  allocationTotal,
  saveAllocationSettings,
  requiredExpenseForm,
  setRequiredExpenseForm,
  addRequiredExpenseItem,
  formatInput,
  showResetConfirm,
  setShowResetConfirm,
  setActiveTab,
  modalFlow,
}) {
  return {
    locale,
    store,
    isEnglish,
    fmt,
    backupNotice,
    familyNotice,
    importPartnerReport,
    removePartnerReport,
    removePartner,
    exportBackup,
    importBackup,
    undoImport,
    openOnboardingReconfigure: onboarding.openOnboardingReconfigure,
    pinEnabled: security.pinEnabled,
    securityForm,
    setSecurityForm,
    securityNotice,
    saveSecurityPin,
    clearSecurityPin,
    lockAppNow,
    showAdvancedDistribution,
    setShowAdvancedDistribution,
    allocationModes,
    setAllocationForm,
    allocationForm,
    handleAllocationInput,
    currentMode,
    payYourselfPercent,
    availableForObligations,
    previewReservedForRequired: previewDistribution.toBalance,
    previewDistribution,
    totalRequiredExpenses: store.requiredExpenses.reduce((sum, item) => sum + item.amount, 0),
    obligationsDelta,
    allocationTotal,
    saveAllocationSettings,
    requiredExpenseForm,
    setRequiredExpenseForm,
    addRequiredExpenseItem,
    formatInput,
    showResetConfirm,
    setShowResetConfirm,
    onConfirmReset: () => {
      store.resetData();
      setShowResetConfirm(false);
      setActiveTab('home');
    },
    onOpenTargetCapital: () => {
      modalFlow.openAmountModal('set_target_capital', store.targetCapital);
    },
    onOpenTargetSafety: () => {
      modalFlow.openAmountModal('set_target_safety', store.targetSafety);
    },
  };
}
